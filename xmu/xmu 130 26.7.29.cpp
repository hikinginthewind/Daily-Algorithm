/*
xmu 130		26.7.29
上一题的二分进阶
维护 b 每次看 a[i] 和 b 的尾巴值
1 a[i]更大 接到 b尾巴
2 尾巴更大 在 b 中二分查找第一个大于 a[i] 的值 替换进去
用 a[i] 潜力更大 且最长的子串的长度只会因为更大被更新 不会缩短或少算 
*/

#include <bits/stdc++.h>
using namespace std;
int n;
int main()
{
	cin >> n;
	int a[n + 1];
	for(int i = 1;i <= n;i++) cin >> a[i];
	int b[n + 1] = {0};
	b[1] = a[1];
	int len = 1;
	for(int i = 2;i <= n;i++)
	{
		if(a[i] > b[len]) b[++len] = a[i];
		else
		{
			int l = 1;
			int r = len;
			while(l <= r)
			{
				int mid = (l + r) / 2;
				if(b[mid] < a[i]) l = mid + 1;
				else r = mid - 1;
			}
			b[l] = a[i];
		}
	}
	cout << len << endl;
	return 0;
}
