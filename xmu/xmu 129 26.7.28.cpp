/*
xmu 129		26.7.28
线性dp找升序
dp[i] 记录到 i 位置的最长上升子序列的 |长度|
更新时向前找到最大的 dp[j] +1 和原 dp[i] 比较更大值即为 dp[i] 
*/

#include <bits/stdc++.h>
using namespace std;
int n;
int main()
{
	cin >> n;
	vector<int> a(n,0);
	int ans = 0;
	for(int i = 0;i < n;i++)
	{
		cin >> a[i];
	}
	vector<int> dp(n,1);
	for(int i = 0;i < n;i++)
	{
		for(int j = i;j >= 0;j--)
		{
			if(a[j] < a[i]) dp[i] = max(dp[i],dp[j] + 1);
		}
		ans = max(ans,dp[i]);
	}
	cout << ans << endl;
	return 0;
}
