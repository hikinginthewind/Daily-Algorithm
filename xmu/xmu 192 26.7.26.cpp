#include <bits/stdc++.h>
using namespace std;
int main()
{
	int m,n;
	cin >> m >> n;
	vector<vector<int>> g(m,vector<int>(n));
	for(int i = 0;i < m;i++)
	{
		for(int j = 0;j < n;j++)
		{
			cin >> g[i][j];
		}
	}
	int dp[m + n][m][m] = {0};
	for(int k = 2;k <= m + n;k++)
	{
		for(int i1 = 1;i1 < m;i1++)
		{
			int j1 = k - i1;
			if(j1 < 1 || j1 > m - 1) continue;
			for(int i2 = 1;i2 < m;i2++)
			{
				int j2 = k - i2;
				if(i1 == i2 || j2 < 1 || j2 > m - 1) continue;
				int val = g[k][i1][i2];
				int best = max({dp[k - 1][i1 - 1][i2 - 1],
				dp[k - 1][i1 - 1][i2],
				dp[k - 1][i1][i2 - 1],
				dp[k - 1][i1][i2]});
				dp[k][i1][i2] = val + best;
			}
		}
	}
	cout << dp[m + n - 2][m - 1][m - 1] << endl;
	return 0;
} 
