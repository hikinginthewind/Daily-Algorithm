/*
K 记录走的步数(两人同一时刻走的步数应相同)
i1 i2 只记录行数 可以用 k 算出对应列数
遍历每个 k 的每个 i1 和 i2 
*/

#include <bits/stdc++.h>
using namespace std;
const int m = 11;
int w[m][m];
int dp[2 * m][m][m];
int main()
{
	int n;
	cin >> n;
	int r;
	int c;
	int num;
	while(cin >> r >> c >> num)
	{
		if(r == 0 && c == 0 && num == 0) break;
		w[r][c] = num;
	}
	for(int k = 2;k <= 2 * n;k++)
	{
		for(int i1 = 1;i1 <= n;i1++)
		{
			int j1 = k - i1;
			if(j1 < 1 || j1 > n) continue;
			for(int i2 = 1;i2 <= n;i2++)
			{
				int j2 = k - i2;
				if(j2 < 1 || j2 > n) continue;
				int val = w[i1][j1];
				if(i1 != i2) val += w[i2][j2];
				int best = max({dp[k - 1][i1 - 1][i2 - 1],
				dp[k - 1][i1 - 1][i2],
				dp[k - 1][i1][i2 - 1],
				dp[k - 1][i1][i2]});
				dp[k][i1][i2] = best + val;
			}
		}
	}
	cout << dp[2 * n][n][n] << endl;
	return 0;	
} 
