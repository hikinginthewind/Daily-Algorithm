/*
xmu 124		26.7.27
线性dp
a 的前 i 个和 b 的前 j 个中重叠最长的长度为 f[i][j]
那么看递推就有几种情况 
1 a[i] == b[j] 计入 ++
2 a[i] != b[j] 不计入 考虑去掉 a[i] 或 b[j] 两种方案中 f 的最大值 
*/
#include <bits/stdc++.h>
using namespace std;
int n,m;
int main()
{
	cin >> n >> m;
	char a[n + 1];
	char b[m + 1];
	cin >> a + 1 >> b + 1;
	vector<vector<int>> f(n + 1,vector<int>(m + 1,0));
	for(int i = 1;i <= n;i++)
		for(int j = 1;j <= m;j++)
		{
			f[i][j] = max(f[i - 1][j],f[i][j - 1]);
			if(a[i] == b[j]) f[i][j] = max(f[i][j],f[i - 1][j - 1] + 1);
		}
	cout << f[n][m] << endl;
	return 0;
}
